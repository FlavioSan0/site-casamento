-- Reserva atômica: evita duas pessoas consumirem a última cota simultaneamente.
create or replace function public.reservar_presente(
  p_evento_id bigint,
  p_presente_id bigint,
  p_reservado_por text
)
returns table (
  presente_id bigint,
  quantidade_reservada integer,
  status text,
  usa_cotas boolean
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_presente public.presentes%rowtype;
  v_nova_quantidade integer;
  v_novo_status text;
begin
  if trim(coalesce(p_reservado_por, '')) = '' then
    raise exception 'Informe seu nome para reservar.';
  end if;

  select *
    into v_presente
    from public.presentes p
   where p.id = p_presente_id
     and p.evento_id = p_evento_id
   for update;

  if not found then
    raise exception 'Presente não encontrado para este evento.';
  end if;

  if v_presente.usa_cotas then
    if v_presente.quantidade_reservada >= v_presente.quantidade_total then
      raise exception 'Todas as cotas deste presente já foram reservadas.';
    end if;
  elsif v_presente.status = 'reservado' or v_presente.quantidade_reservada > 0 then
    raise exception 'Este presente já foi reservado.';
  end if;

  insert into public.reservas_presentes (
    evento_id,
    presente_id,
    reservado_por
  ) values (
    p_evento_id,
    p_presente_id,
    left(trim(p_reservado_por), 120)
  );

  v_nova_quantidade := v_presente.quantidade_reservada + 1;
  v_novo_status := case
    when not v_presente.usa_cotas then 'reservado'
    when v_nova_quantidade >= v_presente.quantidade_total then 'reservado'
    else 'disponivel'
  end;

  update public.presentes p
     set quantidade_reservada = v_nova_quantidade,
         status = v_novo_status
   where p.id = p_presente_id
     and p.evento_id = p_evento_id;

  return query
  select p_presente_id, v_nova_quantidade, v_novo_status, v_presente.usa_cotas;
end;
$$;

create or replace function public.remover_reserva_presente(
  p_evento_id bigint,
  p_reserva_id bigint
)
returns table (
  presente_id bigint,
  quantidade_reservada integer,
  status text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_reserva public.reservas_presentes%rowtype;
  v_presente public.presentes%rowtype;
  v_nova_quantidade integer;
  v_novo_status text;
begin
  select *
    into v_reserva
    from public.reservas_presentes r
   where r.id = p_reserva_id
     and r.evento_id = p_evento_id
   for update;

  if not found then
    raise exception 'Reserva não encontrada.';
  end if;

  select *
    into v_presente
    from public.presentes p
   where p.id = v_reserva.presente_id
     and p.evento_id = p_evento_id
   for update;

  if not found then
    raise exception 'Presente da reserva não encontrado.';
  end if;

  delete from public.reservas_presentes where id = v_reserva.id;

  v_nova_quantidade := greatest(v_presente.quantidade_reservada - 1, 0);
  v_novo_status := case
    when not v_presente.usa_cotas and v_nova_quantidade > 0 then 'reservado'
    else 'disponivel'
  end;

  update public.presentes p
     set quantidade_reservada = v_nova_quantidade,
         status = v_novo_status
   where p.id = v_presente.id;

  return query
  select v_presente.id, v_nova_quantidade, v_novo_status;
end;
$$;

