alter table public.historia_momentos enable row level security;

drop policy if exists "eventos_public_read" on public.eventos;
create policy "eventos_public_read" on public.eventos
for select using (ativo = true or auth.role() = 'authenticated');

drop policy if exists "configuracoes_public_read" on public.configuracoes_evento;
create policy "configuracoes_public_read" on public.configuracoes_evento
for select using (
  auth.role() = 'authenticated'
  or exists (
    select 1 from public.eventos e
    where e.id = configuracoes_evento.evento_id and e.ativo = true
  )
);

drop policy if exists "presentes_public_read" on public.presentes;
create policy "presentes_public_read" on public.presentes
for select using (
  auth.role() = 'authenticated'
  or exists (
    select 1 from public.eventos e
    where e.id = presentes.evento_id and e.ativo = true
  )
);

drop policy if exists "galeria_public_read" on public.galeria_evento;
create policy "galeria_public_read" on public.galeria_evento
for select using (
  auth.role() = 'authenticated'
  or exists (
    select 1 from public.eventos e
    where e.id = galeria_evento.evento_id and e.ativo = true
  )
);

drop policy if exists "historia_public_read" on public.historia_momentos;
create policy "historia_public_read" on public.historia_momentos
for select using (
  auth.role() = 'authenticated'
  or exists (
    select 1 from public.eventos e
    where e.id = historia_momentos.evento_id and e.ativo = true
  )
);

drop policy if exists "confirmacoes_admin_read" on public.confirmacoes;
create policy "confirmacoes_admin_read" on public.confirmacoes
for select to authenticated using (true);

drop policy if exists "reservas_admin_read" on public.reservas_presentes;
create policy "reservas_admin_read" on public.reservas_presentes
for select to authenticated using (true);

drop policy if exists "event_assets_public_read" on storage.objects;
create policy "event_assets_public_read" on storage.objects
for select using (bucket_id = 'event-assets');

commit;
